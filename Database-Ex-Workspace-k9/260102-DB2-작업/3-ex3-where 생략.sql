--- 5. 기본 문법 및 예시

-- 전체 데이터 출력 (조건 없이)
-- sql
SELECT * FROM EMP;
--> 모든 열과 모든 행을 출력 (조건 없음)

-- WHERE 절로 조건 지정 (부서 번호가 30인 경우)
-- sql
SELECT * FROM EMP
WHERE DEPTNO = 30;
--> DEPTNO 열의 값이 30인 행만 출력됨

--- 6. 원리, 구조 (쉬운 비유)

-- **전체 사원 명단 중에서 "30번 부서만 보여줘"**라는 필터링 지시
-- WHERE 절은 **데이터 필터링을 위한 ‘입장 허가증’**
-- 조건을 만족하는 행만 SELECT 결과에 포함됨
-- 조건이 `TRUE` → 포함됨
-- 조건이 `FALSE` → 제외됨

