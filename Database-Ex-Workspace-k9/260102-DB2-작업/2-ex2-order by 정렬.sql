--- 기본 문법 및 예시

-- ① 오름차순 정렬 (기본값)
-- sql
SELECT * FROM EMP
ORDER BY SAL;
-- SAL 기준 오름차순 정렬

-- ② 내림차순 정렬
-- sql
SELECT * FROM EMP
ORDER BY SAL DESC;

-- ③ 여러 열 기준으로 정렬 (각 열에 다른 정렬)
-- sql
SELECT * FROM EMP
ORDER BY DEPTNO ASC, SAL DESC;
--> 부서번호는 오름차순 → 부서 내에서는 급여를 높은 순으로 정렬

-- ④ 열 인덱스로 정렬하기
-- sql
SELECT ENAME, JOB, SAL
FROM EMP
ORDER BY 3 DESC;
--> 3번째 열인 SAL을 기준으로 내림차순 정렬


--- 원리, 구조 (쉬운 비유)

-- 엑셀에서 열을 기준으로 “정렬”하는 기능과 같음
-- 오름차순은 숫자 작은 순, 가나다 순, 과거 날짜 순
-- 내림차순은 숫자 큰 순, 히읗부터, 최신 날짜 순
-- 열 2개 이상 지정하면 첫 번째 기준으로 정렬하고, 동일 값이 있을 때 두 번째 기준 적용

--- 실무 활용 사례

-- **사원 목록을 급여순, 입사일 순으로 정렬**하여 보고서 출력
-- **상품 목록을 가격순, 평점순**으로 정렬하여 UI 구현
-- **게시판 글 목록을 최신 작성일 순**으로 정렬